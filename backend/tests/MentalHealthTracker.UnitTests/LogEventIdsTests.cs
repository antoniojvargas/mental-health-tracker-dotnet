using System.Reflection;
using MentalHealthTracker.Api.Core.Hosting;
using MentalHealthTracker.Infrastructure;
using Microsoft.Extensions.Logging;

namespace MentalHealthTracker.UnitTests;

// Los EventId de los logs son contrato con el agregador de logs (alertas, consultas): no se
// reutilizan ni se renumeran. La tabla de abajo está escrita a mano para que cambiar un número,
// un nombre o un nivel rompa un test a la vista, y los demás tests exigen que NINGÚN log generado
// se quede sin id explícito o con un id repetido.
public sealed class LogEventIdsTests
{
    private static readonly Assembly[] Assemblies =
    [
        typeof(ApiPipeline).Assembly,
        typeof(DependencyInjection).Assembly,
    ];

    // (id, nombre, nivel, método que lo emite)
    public static TheoryData<int, string, LogLevel, string> Catalog => new()
    {
        { 1001, "GoogleCallbackRejected", LogLevel.Warning, "AuthController.LogCallbackRejected" },
        { 1002, "GoogleCallbackFailed", LogLevel.Error, "AuthController.LogCallbackFailed" },
        { 1003, "SessionUserMissing", LogLevel.Warning, "AuthController.LogSessionUserMissing" },
        { 1101, "RequestRejected", LogLevel.Information, "GlobalExceptionHandler.LogHandledAppException" },
        { 1102, "UnhandledException", LogLevel.Error, "GlobalExceptionHandler.LogHandledUnexpectedException" },
        { 1103, "RequestAborted", LogLevel.Debug, "GlobalExceptionHandler.LogRequestAborted" },
        { 1201, "HealthCheckFailed", LogLevel.Error, "HealthEndpoints.LogHealthCheckFailed" },
        { 1301, "ShutdownClosingConnections", LogLevel.Information, "GracefulShutdownService.LogClosingConnections" },
        { 1302, "ShutdownClosingPool", LogLevel.Information, "GracefulShutdownService.LogClosingPool" },
        { 1401, "RealtimeSendFailed", LogLevel.Warning, "LogEventEmitter.LogSendFailed" },
        { 2001, "MigrationsApplying", LogLevel.Information, "DatabaseInitializer.LogApplyingMigrations" },
        { 2002, "MigrationsApplied", LogLevel.Information, "DatabaseInitializer.LogMigrationsApplied" },
        { 2003, "DatabaseNotReady", LogLevel.Warning, "DatabaseInitializer.LogDatabaseNotReady" },
        { 2004, "DatabaseUnreachable", LogLevel.Error, "DatabaseInitializer.LogDatabaseUnreachable" },
        { 2101, "DemoSeedingStarted", LogLevel.Information, "DatabaseSeeder.LogSeedingStarted" },
        { 2102, "DemoSeedingCompleted", LogLevel.Information, "DatabaseSeeder.LogSeedingCompleted" },
    };

    private static List<(string Method, LoggerMessageAttribute Attribute)> GeneratedLogs() =>
        Assemblies
            .SelectMany(assembly => assembly.GetTypes())
            .SelectMany(type => type
                .GetMethods(BindingFlags.Static | BindingFlags.Instance | BindingFlags.Public | BindingFlags.NonPublic | BindingFlags.DeclaredOnly)
                .Select(method => (Method: $"{type.Name}.{method.Name}", Attribute: method.GetCustomAttribute<LoggerMessageAttribute>())))
            .Where(entry => entry.Attribute is not null)
            .Select(entry => (entry.Method, entry.Attribute!))
            .ToList();

    [Theory]
    [MemberData(nameof(Catalog))]
    public void EveryLogHasItsPinnedEventIdNameAndLevel(int id, string name, LogLevel level, string method)
    {
        var log = Assert.Single(GeneratedLogs(), entry => entry.Method == method);

        Assert.Equal(id, log.Attribute.EventId);
        Assert.Equal(name, log.Attribute.EventName);
        Assert.Equal(level, log.Attribute.Level);
    }

    [Fact]
    public void TheCatalogCoversEveryGeneratedLog()
    {
        var pinned = Catalog.Select(row => (string)row[3]).ToHashSet();

        Assert.DoesNotContain(GeneratedLogs().Select(entry => entry.Method), method => !pinned.Contains(method));
        Assert.Equal(pinned.Count, GeneratedLogs().Count);
    }

    [Fact]
    public void NoGeneratedLogRelyOnAnAutoGeneratedEventId()
    {
        Assert.All(GeneratedLogs(), log =>
        {
            Assert.True(log.Attribute.EventId > 0, $"{log.Method} no declara un EventId explícito.");
            Assert.False(string.IsNullOrWhiteSpace(log.Attribute.EventName), $"{log.Method} no declara un EventName.");
        });
    }

    [Fact]
    public void EventIdsAreUniqueAcrossBothAssemblies()
    {
        var duplicated = GeneratedLogs()
            .GroupBy(log => log.Attribute.EventId)
            .Where(group => group.Count() > 1)
            .Select(group => $"{group.Key}: {string.Join(", ", group.Select(log => log.Method))}")
            .ToList();

        Assert.Empty(duplicated);
    }

    [Fact]
    public void EventNamesAreUniqueToo()
    {
        var duplicated = GeneratedLogs()
            .GroupBy(log => log.Attribute.EventName)
            .Where(group => group.Count() > 1)
            .Select(group => group.Key)
            .ToList();

        Assert.Empty(duplicated);
    }

    [Fact]
    public void TheApiUsesTheThousandsAndInfrastructureTheTwoThousands()
    {
        foreach (var log in GeneratedLogs())
        {
            var fromInfrastructure = log.Method is "DatabaseInitializer.LogApplyingMigrations" or "DatabaseInitializer.LogMigrationsApplied"
                or "DatabaseInitializer.LogDatabaseNotReady" or "DatabaseInitializer.LogDatabaseUnreachable"
                or "DatabaseSeeder.LogSeedingStarted" or "DatabaseSeeder.LogSeedingCompleted";

            Assert.Equal(fromInfrastructure ? 2 : 1, log.Attribute.EventId / 1000);
        }
    }
}
